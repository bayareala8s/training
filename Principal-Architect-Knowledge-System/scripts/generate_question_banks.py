ROOT = Path(__file__).resolve().parent.parent / "interview" / "question-bank"

RUBRIC = {
    "excellent": "Principal-level depth with safety/liveness separation, operational implications, and explicit tradeoffs.",
    "good": "Correct mechanism and tradeoffs; minor gaps in ops or organizational scope.",
    "adequate": "Surface understanding; struggles under partition or consistency follow-ups.",
    "weak": "Hand-waving, confused guarantees, or no failure model.",
}


def q(
    id: str,
    domain: str,
    topic: str,
    question: str,
    signals: list[str],
    red_flags: list[str],
    follow_ups: list[str],
    question_type: str = "technical-deep-dive",
    difficulty: str = "principal",
    minutes: int = 15,
    company_patterns: list[str] | None = None,
    outline: str = "",
) -> dict:
    return {
        "id": id,
        "domain": domain,
        "topic": topic,
        "difficulty": difficulty,
        "question_type": question_type,
        "company_patterns": company_patterns or [],
        "estimated_minutes": minutes,
        "question": question.strip(),
        "expected_signals": signals,
        "red_flags": red_flags,
        "follow_ups": follow_ups,
        "scoring_rubric": dict(RUBRIC),
        "strong_answer_outline": outline.strip(),
    }


def dump_yaml_header(domain: str, count: int) -> str:
    return textwrap.dedent(f"""\
        version: 1
        domain: {domain}
        last_updated: 2026-07-25
        difficulty: principal
        total_questions: {count}
        template: templates/interview-question-template.md
        scoring_rubrics:
          - interview/scoring-rubrics/principal-system-design.md
          - interview/scoring-rubrics/distributed-systems-deep-dive.md

        questions:
    """)


def indent_block(lines: list[str], spaces: int = 4) -> str:
    pad = " " * spaces
    return "\n".join(pad + line for line in lines)


def render_question(qd: dict) -> str:
    lines = [
        f"- id: {qd['id']}",
        f"  domain: {qd['domain']}",
        f"  topic: {qd['topic']}",
        f"  difficulty: {qd['difficulty']}",
        f"  question_type: {qd['question_type']}",
        f"  company_patterns: {qd['company_patterns']}",
        f"  estimated_minutes: {qd['estimated_minutes']}",
        f"  question: |",
    ]
    for line in qd["question"].split("\n"):
        lines.append(f"    {line}")
    lines.append("  expected_signals:")
    for s in qd["expected_signals"]:
        lines.append(f"    - {s}")
    lines.append("  red_flags:")
    for r in qd["red_flags"]:
        lines.append(f"    - {r}")
    lines.append("  follow_ups:")
    for f in qd["follow_ups"]:
        lines.append(f"    - {f}")
    lines.append("  scoring_rubric:")
    for k, v in qd["scoring_rubric"].items():
        lines.append(f"    {k}: \"{v}\"")
    lines.append("  strong_answer_outline: |")
    for line in qd["strong_answer_outline"].split("\n"):
        lines.append(f"    {line}")
    return "\n".join(lines)


