def write_bank(filename: str, domain: str, questions: list[dict]) -> None:
    parts = [dump_yaml_header(domain, len(questions))]
    parts.extend(render_question(qd) for qd in questions)
    path = ROOT / filename
    path.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {path} ({len(questions)} questions)")


